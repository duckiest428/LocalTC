_UNKNOWN: set[str] = set()


def reworded(text: str, code: str) -> str:
    """``text`` (an English message, pieces between commas) in ``code``; a piece nothing knows is kept as it is."""
    words = WORDS.get(code)
    if words is None or not text.strip():
        return text
    separator = "，" if code == "zh" else ", "
    pieces = [p for p in re.split(r",\s*", text) if p.strip()]
    return separator.join(_piece(p.strip(), words, code) for p in pieces)


def _piece(piece: str, words: dict[str, str], code: str, depth: int = 0) -> str:
    for key, pattern in _COMPILED:
        if key in words and (m := pattern.fullmatch(piece)) is not None:
            groups = [(_piece(g.strip(), words, code, depth + 1) if g and depth < 3 else (g or "")).strip()
                      for g in m.groups()]
            return re.sub(r"\s+", " ", words[key].format(*groups)).strip()
    if depth == 0 and piece not in _UNKNOWN and re.fullmatch(r"[a-z][a-z ']+", piece):  # (English words, not a name)
        _UNKNOWN.add(piece)
        log.info("No %s words for %r: said in English", code, piece)
    return piece
