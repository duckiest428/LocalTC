def latin(word: str) -> str:
    """A name speech-to-text wrote in Cyrillic, back in Latin letters for the callsigns and fixes ("Аэрофлот" ->
    "aeroflot")."""
    return "".join(_ROMAN.get(c, c) for c in word.lower())


